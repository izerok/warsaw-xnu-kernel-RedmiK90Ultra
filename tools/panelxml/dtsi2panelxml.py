#!/usr/bin/env python3
"""Convert a Qualcomm kernel panel .dtsi (Xiaomi display-devicetree form)
into a QCOM-UEFI DisplayDxe Panel XML of the form Mu-Silicium packages
carry in <device>Pkg/RawFiles (e.g. annibalePkg's
Panel_xiaomi_p11_42_0d_0a_dsc_cmd.xml).

Adapted from annibale's own generator, tools/dts2panelxml.py in
iola1999/hackios-redmi-k90-annibale, which produced the shipped P11 XML
from a merged DTS dumped off the phone. The output template below is that
generator's, unchanged. What changed is the input side only:

  * input is the panel .dtsi as published in
    MiCode/vendor_qcom_opensource_display-devicetree (decimal or hex cell
    values, comments, and the per-timing #include of the panel-common
    file are all resolved here; the original only understood the hex
    cells of a decompiled DTB dump);
  * the timing mode is selected explicitly (--framerate, default 60:
    the mode the shipped P11 XML was made from -- its DSIRefreshRate is
    0x3c0000 and its init sequence is the 60 Hz mode's on-command);
  * PanelName defaults to the qcom,mdss-dsi-panel-name property minus
    its trailing " cmd mode dsc dsi panel" (the original took it as a
    command-line argument; the derived value is identical on the P11
    regression sample);
  * lane count is counted from the qcom,mdss-dsi-lane-N-state
    properties (the original read a differently-named property that
    does not exist in these trees and fell back to 4).

Kernel DTS command blob:  [type last vc ack wait len_hi len_lo] is NOT
the layout; the arrays in these trees serialise each command as
[type, last, vc, ack, wait, 0, len, data...] with len < 256 and
wait < 256 (byte 5 is zero in every command of both regression panels;
this converter refuses a nonzero byte 5 rather than guess).

UEFI XML command line:    <type> <data bytes...> [<delay>]   (delay
trailing decimal, only when the kernel command's wait field is nonzero;
commands with len 0 or type 0 are dropped, as in the original).

usage: dtsi2panelxml.py <panel.dtsi> <out.xml> [--framerate 60]
                        [--panel-name NAME] [--verify-against XML]

--verify-against compares the generated bytes with an existing XML and,
on mismatch, prints an element/line level diff and exits 3.
"""
import os
import re
import sys

# ---------------------------------------------------------------- DTS input

def load_dtsi(path, depth=0):
    """Read a .dtsi, inlining #include "..." lines (paths relative to the
    including file) and stripping comments (quote-aware)."""
    if depth > 8:
        raise ValueError('include depth exceeded at %s' % path)
    with open(path) as f:
        raw = f.read()
    base = os.path.dirname(os.path.abspath(path))
    out = []
    for line in raw.splitlines():
        m = re.match(r'\s*#include\s+"([^"]+)"\s*$', line)
        if m:
            inc = os.path.join(base, m.group(1))
            out.append(load_dtsi(inc, depth + 1))
        elif re.match(r'\s*#', line):
            continue  # other preprocessor lines carry no panel data
        else:
            out.append(line)
    return strip_comments('\n'.join(out))


def strip_comments(text):
    out = []
    i, n = 0, len(text)
    in_str = False
    while i < n:
        c = text[i]
        if in_str:
            out.append(c)
            if c == '"':
                in_str = False
            i += 1
        elif c == '"':
            in_str = True
            out.append(c)
            i += 1
        elif c == '/' and i + 1 < n and text[i + 1] == '*':
            j = text.find('*/', i + 2)
            if j < 0:
                raise ValueError('unterminated /* comment')
            i = j + 2
        elif c == '/' and i + 1 < n and text[i + 1] == '/':
            j = text.find('\n', i + 2)
            i = n if j < 0 else j
        else:
            out.append(c)
            i += 1
    return ''.join(out)


class Node(object):
    def __init__(self, name):
        self.name = name
        self.props = {}      # name -> raw value string, or None for boolean
        self.children = []   # list[Node]

    def has(self, name):
        return name in self.props

    def cells(self, name, default=None):
        v = self.props.get(name)
        if v is None:
            return default
        vals = []
        for group in re.findall(r'<([^>]*)>', v):
            for tok in group.split():
                if tok.startswith('&'):
                    raise ValueError('%s: phandle in numeric prop %s' % (self.name, name))
                vals.append(int(tok, 0))
        return vals

    def cell(self, name, default=None):
        c = self.cells(name)
        return default if not c else c[0]

    def byte_array(self, name):
        v = self.props.get(name)
        if v is None:
            return None
        m = re.search(r'\[(.*)\]', v, re.S)
        if not m:
            raise ValueError('%s: %s is not a byte array' % (self.name, name))
        out = []
        for tok in m.group(1).split():
            if re.fullmatch(r'0[xX][0-9a-fA-F]+', tok):
                b = int(tok, 16)
            elif re.fullmatch(r'[0-9a-fA-F]{2}', tok):
                b = int(tok, 16)
            else:
                raise ValueError('%s: bad byte token %r in %s' % (self.name, tok, name))
            if b > 0xFF:
                raise ValueError('%s: byte > 0xff in %s' % (self.name, name))
            out.append(b)
        return out

    def string(self, name, default=None):
        v = self.props.get(name)
        if v is None:
            return default
        m = re.search(r'"([^"]*)"', v)
        return m.group(1) if m else default


def parse_dt(text):
    """Minimal DTS parser: returns a root Node whose children are the
    top-level nodes. Property values are kept as raw text."""
    pos = 0
    n = len(text)

    def skip_ws():
        nonlocal pos
        while pos < n and text[pos] in ' \t\r\n':
            pos += 1

    def parse_items(node):
        nonlocal pos
        while True:
            skip_ws()
            if pos >= n:
                return
            if text[pos] == '}':
                pos += 1
                return
            # read a header: property name, or [label:] node-name
            start = pos
            while pos < n and text[pos] not in '=;{}':
                pos += 1
            header = text[start:pos].strip()
            if pos >= n:
                raise ValueError('truncated item %r' % header)
            c = text[pos]
            if c == ';':                      # boolean property
                pos += 1
                node.props[header] = None
            elif c == '=':                    # valued property
                pos += 1
                vstart = pos
                depth_b = depth_c = 0
                in_str = False
                while pos < n:
                    ch = text[pos]
                    if in_str:
                        if ch == '"':
                            in_str = False
                    elif ch == '"':
                        in_str = True
                    elif ch == '[':
                        depth_b += 1
                    elif ch == ']':
                        depth_b -= 1
                    elif ch == '<':
                        depth_c += 1
                    elif ch == '>':
                        depth_c -= 1
                    elif ch == ';' and depth_b == 0 and depth_c == 0:
                        break
                    pos += 1
                if pos >= n:
                    raise ValueError('unterminated value for %r' % header)
                node.props[header] = text[vstart:pos].strip()
                pos += 1  # consume ';'
            elif c == '{':                    # child node
                pos += 1
                name = header.split(':', 1)[-1].strip()
                child = Node(name)
                node.children.append(child)
                parse_items(child)
                skip_ws()
                if pos < n and text[pos] == ';':
                    pos += 1
            else:                             # '}' handled above
                raise ValueError('unexpected %r after %r' % (c, header))

    root = Node('')
    parse_items(root)
    return root


def find_panel_node(root):
    hits = []

    def walk(node):
        if node.has('qcom,mdss-dsi-panel-name'):
            hits.append(node)
        for ch in node.children:
            walk(ch)

    walk(root)
    if len(hits) != 1:
        raise ValueError('expected exactly one panel node, found %d' % len(hits))
    return hits[0]

# ------------------------------------------------------------- command emit

def emit_cmds(bs):
    """Kernel command stream -> UEFI per-line form (original semantics)."""
    out = []
    i = 0
    while i < len(bs):
        if i + 7 > len(bs):
            raise ValueError('truncated command header at offset %d' % i)
        typ, wait = bs[i], bs[i + 4]
        if bs[i + 5] != 0:
            raise ValueError(
                'command at offset %d has nonzero header byte 5 (0x%02x): '
                'encoding outside the evidenced layout, refusing to guess'
                % (i, bs[i + 5]))
        ln = bs[i + 6]
        data = bs[i + 7:i + 7 + ln]
        if len(data) < ln:
            raise ValueError('truncated command payload at offset %d' % i)
        if ln and typ:
            line = '%02X %s' % (typ, ' '.join('%02X' % b for b in data))
            if wait:
                line += ' %d' % wait
            out.append(' ' + line)
        i += 7 + ln
    return out

# ------------------------------------------------------------------- main

def convert(dtsi_path, framerate=60, panel_name=None):
    root = parse_dt(load_dtsi(dtsi_path))
    panel = find_panel_node(root)

    timings = None
    for ch in panel.children:
        if ch.name == 'qcom,mdss-dsi-display-timings':
            timings = ch
    if timings is None:
        raise ValueError('panel node has no qcom,mdss-dsi-display-timings')
    modes = [ch for ch in timings.children if ch.name.startswith('timing')]
    if not modes:
        raise ValueError('no timing modes found')

    sel = [m for m in modes
           if m.cell('qcom,mdss-dsi-panel-framerate') == framerate]
    if len(sel) != 1:
        raise ValueError('expected exactly one %d Hz timing mode, found %d'
                         % (framerate, len(sel)))
    mode = sel[0]

    # The panel-common include lands inside every timing node; the shared
    # (resolution/clock/DSC) values must agree across modes.
    shared = ['qcom,mdss-dsi-panel-width', 'qcom,mdss-dsi-panel-height',
              'qcom,mdss-dsi-panel-clockrate', 'qcom,mdss-dsc-slice-width',
              'qcom,mdss-dsc-slice-height', 'qcom,mdss-dsc-version']
    for name in shared:
        vals = {m.cell(name) for m in modes}
        if len(vals) != 1:
            raise ValueError('%s differs across timing modes: %s' % (name, vals))

    def req(node, name):
        v = node.cell(name)
        if v is None:
            raise ValueError('missing required property %s' % name)
        return v

    w = req(mode, 'qcom,mdss-dsi-panel-width')
    h = req(mode, 'qcom,mdss-dsi-panel-height')
    hfp = req(mode, 'qcom,mdss-dsi-h-front-porch')
    hbp = req(mode, 'qcom,mdss-dsi-h-back-porch')
    hpw = req(mode, 'qcom,mdss-dsi-h-pulse-width')
    vfp = req(mode, 'qcom,mdss-dsi-v-front-porch')
    vbp = req(mode, 'qcom,mdss-dsi-v-back-porch')
    vpw = req(mode, 'qcom,mdss-dsi-v-pulse-width')
    hskew = mode.cell('qcom,mdss-dsi-h-sync-skew', 0)
    hl = mode.cell('qcom,mdss-dsi-h-left-border', 0)
    hr = mode.cell('qcom,mdss-dsi-h-right-border', 0)
    vt = mode.cell('qcom,mdss-dsi-v-top-border', 0)
    vb = mode.cell('qcom,mdss-dsi-v-bottom-border', 0)
    fps = req(mode, 'qcom,mdss-dsi-panel-framerate')
    clk = req(mode, 'qcom,mdss-dsi-panel-clockrate')
    dsc_w = req(mode, 'qcom,mdss-dsc-slice-width')
    dsc_h = req(mode, 'qcom,mdss-dsc-slice-height')
    dsc_ver = req(mode, 'qcom,mdss-dsc-version')
    dsc_scr = mode.cell('qcom,mdss-dsc-scr-version', 0)
    refresh = fps << 16

    # Template constants of the original generator, each guarded by the
    # dtsi property it corresponds to (single-sample evidence: P11).
    if panel.string('qcom,mdss-dsi-panel-type') != 'dsi_cmd_mode':
        raise ValueError('panel-type is not dsi_cmd_mode; template unevidenced')
    if panel.cell('qcom,mdss-dsi-bpp') != 30:
        raise ValueError('DSIColorFormat 36 is evidenced only for bpp 30')
    if panel.string('qcom,mdss-dsi-traffic-mode') != 'burst_mode':
        raise ValueError('DSITrafficMode 1 is evidenced only for burst_mode')
    if panel.string('qcom,mdss-dsi-lane-map') != 'lane_map_0123':
        raise ValueError('DSICmdSwapInterface False evidenced only for lane_map_0123')
    if mode.string('qcom,compression-mode') != 'dsc':
        raise ValueError('template covers DSC panels only')
    for prop in ('qcom,mdss-dsi-te-check-enable',
                 'qcom,mdss-dsi-te-using-te-pin',
                 'qcom,mdss-dsi-lp11-init'):
        if not panel.has(prop):
            raise ValueError('%s absent; corresponding XML True is unevidenced' % prop)
    lanes = sum(1 for i in range(8)
                if panel.has('qcom,mdss-dsi-lane-%d-state' % i))
    if lanes == 0:
        raise ValueError('no lane-N-state properties found')
    virt = panel.cell('qcom,mdss-dsi-virtual-channel-id', 0)
    ctrl = panel.cell('qcom,dsi-ctrl-num', 0)

    if panel_name is None:
        full = panel.string('qcom,mdss-dsi-panel-name')
        suffix = ' cmd mode dsc dsi panel'
        if not full or not full.endswith(suffix):
            raise ValueError('cannot derive PanelName from %r; pass --panel-name' % full)
        panel_name = full[:-len(suffix)]

    on = emit_cmds(mode.byte_array('qcom,mdss-dsi-on-command'))

    xml = f"""<?xml version='1.0' encoding='utf-8'?>
<PanelName>{panel_name}</PanelName>
<PanelDescription>{panel_name} dsc cmd panel ({w}*{h} dsi-timing, from the device tree of the phone)</PanelDescription>
<Group id='Active Timing'>
 <HorizontalActive>{w}</HorizontalActive>
 <HorizontalFrontPorch>{hfp}</HorizontalFrontPorch>
 <HorizontalBackPorch>{hbp}</HorizontalBackPorch>
 <HorizontalSyncPulse>{hpw}</HorizontalSyncPulse>
 <HorizontalSyncSkew>{hskew}</HorizontalSyncSkew>
 <HorizontalLeftBorder>{hl}</HorizontalLeftBorder>
 <HorizontalRightBorder>{hr}</HorizontalRightBorder>
 <VerticalActive>{h}</VerticalActive>
 <VerticalFrontPorch>{vfp}</VerticalFrontPorch>
 <VerticalBackPorch>{vbp}</VerticalBackPorch>
 <VerticalSyncPulse>{vpw}</VerticalSyncPulse>
 <VerticalSyncSkew>0</VerticalSyncSkew>
 <VerticalTopBorder>{vt}</VerticalTopBorder>
 <VerticalBottomBorder>{vb}</VerticalBottomBorder>
 <InvertDataPolarity>False</InvertDataPolarity>
 <InvertVsyncPolairty>False</InvertVsyncPolairty>
 <InvertHsyncPolarity>False</InvertHsyncPolarity>
 <BorderColor>0x0</BorderColor>
</Group>
<Group id='Display Interface'>
 <InterfaceType>9</InterfaceType>
 <InterfaceColorFormat>3</InterfaceColorFormat>
</Group>
<Group id='DSI Interface'>
 <DSIBitClockFrequency>{clk}</DSIBitClockFrequency>
 <DSIChannelId>2</DSIChannelId>
 <DSIVirtualId>{virt}</DSIVirtualId>
 <DSIColorFormat>36</DSIColorFormat>
 <DSITrafficMode>1</DSITrafficMode>
 <DSILanes>{lanes}</DSILanes>
 <DSIRefreshRate>0x{refresh:x}</DSIRefreshRate>
 <DSISSCConfig>0</DSISSCConfig>
 <DSICmdSwapInterface>False</DSICmdSwapInterface>
 <DSICmdUsingTrigger>False</DSICmdUsingTrigger>
 <DSIEnableAutoRefresh>True</DSIEnableAutoRefresh>
 <DSIAutoRefreshFrameNumDiv>1</DSIAutoRefreshFrameNumDiv>
 <DSITECheckEnable>True</DSITECheckEnable>
 <DSITEUsingDedicatedTEPin>True</DSITEUsingDedicatedTEPin>
 <DSITEvSyncStartPos>{h}</DSITEvSyncStartPos>
 <DSITEvSyncInitVal>{h}</DSITEvSyncInitVal>
 <DSITEvSyncSelect>0</DSITEvSyncSelect>
 <DSIDSCEnable>True</DSIDSCEnable>
 <DSIDSCMajor>{dsc_ver >> 4}</DSIDSCMajor>
 <DSIDSCMinor>{dsc_ver & 0xF}</DSIDSCMinor>
 <DSIDSCScr>{dsc_scr}</DSIDSCScr>
 <DSIDSCProfileID>0x0</DSIDSCProfileID>
 <DSIDSCSliceWidth>{dsc_w}</DSIDSCSliceWidth>
 <DSIDSCSliceHeight>{dsc_h}</DSIDSCSliceHeight>
 <DSIControllerMapping>
  {ctrl:02d}
 </DSIControllerMapping>
 <DSILP11AtInit>True</DSILP11AtInit>
</Group>
<DSIInitSequence>
{chr(10).join(on)}
</DSIInitSequence>
"""
    info = ('%dx%d @%dHz clk=%d lanes=%d dsc=%d.%d slice=%dx%d init_cmds=%d'
            % (w, h, fps, clk, lanes, dsc_ver >> 4, dsc_ver & 0xF,
               dsc_w, dsc_h, len(on)))
    return xml, info


def verify(gen_text, ref_path):
    """Structured diff of generated text against a reference XML.
    Returns a list of human-readable difference lines (empty = equal)."""
    ref = open(ref_path).read()
    if gen_text == ref:
        return []
    diffs = []
    gl = gen_text.splitlines()
    rl = ref.splitlines()
    # element-level: everything before <DSIInitSequence>
    def head(lines):
        out = {}
        for ln in lines:
            if ln.startswith('<DSIInitSequence'):
                break
            out[ln.strip()] = out.get(ln.strip(), 0) + 1
        return out
    gh, rh = head(gl), head(rl)
    for k in sorted(set(gh) | set(rh)):
        if gh.get(k) != rh.get(k):
            diffs.append('header line differs: gen=%r ref=%r (count %s vs %s)'
                         % (k if k in gh else None, k if k in rh else None,
                            gh.get(k, 0), rh.get(k, 0)))
    def seq(lines):
        m = False
        out = []
        for ln in lines:
            if ln.startswith('<DSIInitSequence'):
                m = True
                continue
            if ln.startswith('</DSIInitSequence'):
                break
            if m:
                out.append(ln)
        return out
    gs, rs = seq(gl), seq(rl)
    if len(gs) != len(rs):
        diffs.append('init sequence length differs: gen %d lines, ref %d lines'
                     % (len(gs), len(rs)))
    for i, (a, b) in enumerate(zip(gs, rs)):
        if a != b:
            diffs.append('init line %d differs:\n  gen: %s\n  ref: %s' % (i, a, b))
            if len(diffs) > 20:
                diffs.append('... (further init diffs truncated)')
                break
    return diffs


def main(argv):
    args = []
    opts = {}
    it = iter(argv[1:])
    for a in it:
        if a == '--framerate':
            opts['framerate'] = int(next(it), 0)
        elif a == '--panel-name':
            opts['panel_name'] = next(it)
        elif a == '--verify-against':
            opts['verify'] = next(it)
        elif a.startswith('--'):
            sys.stderr.write('unknown option %s\n' % a)
            return 2
        else:
            args.append(a)
    if len(args) != 2:
        sys.stderr.write(__doc__.split('usage:')[1].split('\n\n')[0] + '\n')
        return 2
    xml, info = convert(args[0], framerate=opts.get('framerate', 60),
                        panel_name=opts.get('panel_name'))
    with open(args[1], 'w') as f:
        f.write(xml)
    print('%s: %s' % (args[1], info))
    if 'verify' in opts:
        diffs = verify(xml, opts['verify'])
        if diffs:
            print('VERIFY FAILED against %s:' % opts['verify'])
            for d in diffs:
                print(' ' + d)
            return 3
        print('VERIFY OK: byte-identical to %s' % opts['verify'])
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
