#!/usr/bin/env python3
"""Make the static wallpaper used by the 23G90 wallpaper-window fallback.

The poster pipeline (MercuryPosterExtension / PosterBoard) is not running on this port, so
_SBWallpaperSecureWindow ends up with an empty contents and a black background. Until that is
fixed, paint a self-contained dark gradient here and let libredwood-sb26 set it as the window
layer's contents. This file is generated by us; no Apple asset is copied.
"""
import os
from PIL import Image, ImageOps, ImageDraw, ImageFilter, ImageChops

W, H = 1280, 2772
OUT = os.environ.get("WALLPAPER_OUT", "root/share/wallpaper.png")

base = ImageOps.colorize(
    Image.linear_gradient("L").resize((W, H), Image.BICUBIC),
    black=(3, 5, 14), white=(24, 32, 74),
)

def glow(box, color, radius):
    layer = Image.new("RGB", (W, H), (0, 0, 0))
    ImageDraw.Draw(layer).ellipse(box, fill=color)
    return layer.filter(ImageFilter.GaussianBlur(radius))

base = ImageChops.add(base, glow((-420, 120, 1500, 1900), (46, 38, 104), 360))
base = ImageChops.add(base, glow((180, 1500, 1500, 3300), (16, 44, 78), 320))
base = ImageChops.add(base, glow((-500, 2100, 780, 3100), (34, 16, 56), 300))

os.makedirs(os.path.dirname(OUT), exist_ok=True)
base.save(OUT, "PNG", optimize=True)
print("wallpaper: %s %dx%d %d bytes" % (OUT, W, H, os.path.getsize(OUT)))
